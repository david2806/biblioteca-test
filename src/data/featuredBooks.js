// Helper function to get books by category
export const getBooksByCategory = (categoryName) => {
  const category = categories.find(cat => cat.name === categoryName);
  if (!category) return [];
  
  return category.bookIds
    .map(id => featuredBooks.find(book => book.id === id))
    .filter(Boolean);
};

// Get random featured book
export const getRandomFeaturedBook = () => {
  return featuredBooks[Math.floor(Math.random() * featuredBooks.length)];
};
